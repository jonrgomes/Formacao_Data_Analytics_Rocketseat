# Sintxe de um set:
frutas = {"banara", "uva", "laranja"}
print(frutas)
print(type(frutas))

# Criar um set vazio:
frutas1 = set()
print(type(frutas1))

# Não é possível utilizar valores duplicados em sets:
numeros = {1, 2, 3, 4, 4, 4, 4, 5, 6, 7, 7, 8}
frutas = {"banana", "uva", "banana", "maçã"}

print(numeros)
print(frutas)

