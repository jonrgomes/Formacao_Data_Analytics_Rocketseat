# Sintaxe do comando if
"""
if condição: se a condição for verdadeira 
    Executa esse bloco de comandos
"""

# Exemplo com if
idade = 10
if idade >= 18:
    print('Você é maior de idade!')

# Sintaxe do comando if-else
"""
if condição: se a condição for verdadeira 
else condição: se for falsa
"""

# Exemplo com if-else
idade = 10
if idade >= 18:
    print('Você é maior de idade!')
else:
    print('Você é menor de idade!')