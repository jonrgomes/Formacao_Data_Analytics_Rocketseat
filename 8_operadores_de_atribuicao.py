print(qtd)

# Operadores de divisão (/=): 
qtd = 5
qtd /= 3
print(qtd)

# Operadores de divisão sem resto (//=):
qtd = 5
qtd //= 3
print(qtd)

# Operadores com potencia (**=):
qtd = 5
qtd **= 3
print(qtd)

# Operador com o resto da divisão (%=)
