# Tamanho de uma listas:
cores = ["Preto", "Azul", "Vermelho"]
print(len(cores))

# Inserindo dados em um lista (append):
print(cores[2])
cores.append("Liláz")
print(cores)

# Inserindo dados em uma posiçao especifíca: (insert):
frutas = ["Goiaba", "Laranja", "Abacates"]
frutas.insert(0, "Pera")
print(frutas)
